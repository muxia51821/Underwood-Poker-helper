import { test, expect } from '@playwright/test';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { openWorkbenchMode } from './helpers/workbench.js';
import { readPracticeState } from './helpers/practice-state.js';
const variants=[{name:'desktop',width:1440,height:1000},{name:'mobile',width:390,height:844}];
if(process.env.E2E_OUT_DIR)variants.push({name:'offline',width:390,height:844,file:true});
for(const v of variants)test('two-street research, continuous decisions, refresh and frozen history: '+v.name,async({page})=>{
  await page.setViewportSize(v);
  await page.addInitScript(()=>{Math.random=()=>0;});
  if(v.file)await page.context().setOffline(true);
  await page.goto(v.file?pathToFileURL(join(process.env.E2E_OUT_DIR,'index.html')).href+'#safemode':'/#safemode');
  await openWorkbenchMode(page,'study');await page.locator('[data-study-view=solutions]').click();
  await page.locator('[data-solution-pack]').selectOption('turn-river-half-pot');
  await expect(page.locator('.solution-conditions')).toContainText('可选动作：过牌、下注半池；面对下注：弃牌、跟注。');
  await expect(page.locator('.solution-path button')).toHaveCount(1);
  await page.locator('[data-solution-node="root/check"]').click();
  await page.locator('[data-solution-node="root/check/bet:5"]').click();
  await page.locator('[data-solution-node="root/check/bet:5/fold"]').click();
  await expect(page.locator('[data-solution-terminal]')).toContainText('OOP 弃牌，IP 赢得底池');
  await page.locator('[data-solution-line]').click();
  await expect(page.locator('[data-practice-config=solutionMode]')).toHaveValue('line');
  await page.locator('[data-practice-action=start]').click();
  await expect(page.locator('#practiceWorkspace .solution-values')).toHaveCount(0);
  await expect(page.locator('.practice-context')).toContainText('转牌');
  await page.locator('[name=practiceChoice][value=check]').check();
  await page.locator('[data-practice-action=submit]').click();
  await page.locator('[data-practice-action=next]').click();
  await expect(page.locator('.practice-context')).toContainText('河牌');
  await expect(page.locator('#practiceWorkspace .solution-values')).toHaveCount(0);
  const before=(await readPracticeState(page)).sessions[0];
  expect(before.questions).toHaveLength(2);expect(before.questions[1].context.board).toHaveLength(5);
  expect(before.questions[0].solution.combo).toBe(before.questions[1].solution.combo);
  await page.locator('[data-practice-reason]').fill('检查河牌变化与对手继续范围');
  await page.reload();await openWorkbenchMode(page,'practice');
  if(await page.locator('[data-practice-action=continue]').isVisible())await page.locator('[data-practice-action=continue]').click();
  await expect(page.locator('[data-practice-reason]')).toHaveValue('检查河牌变化与对手继续范围');
  await expect(page.locator('#practiceWorkspace .solution-values')).toHaveCount(0);
  await page.locator('[name=practiceChoice][value=check]').check();await page.locator('[data-practice-action=submit]').click();
  await expect(page.locator('#practiceWorkspace .solution-values')).toHaveCount(1);
  await page.locator('[data-practice-action=next]').click();
  await expect(page.locator('#practiceContent')).toContainText('这条行动线已结束');
  await page.locator('#practiceContent details summary').last().click();
  await page.locator('[data-practice-solution-question]').last().click();
  await expect(page.locator('[data-solution-snapshot]')).toContainText('正在查看本轮冻结答案版本');expect((await readPracticeState(page)).sessions[0].solutionSnapshot.contentHash).toBe(before.solutionSnapshot.contentHash);
  await expect(page.locator('[data-solution-current-board]')).toContainText('当前公共牌');
  await expect(page.locator('[data-solution-node-state]')).toContainText('当前由OOP决策');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});

for(const v of variants)test('IP decisions, marked-node replay and same-branch river comparison: '+v.name,async({page})=>{
  await page.setViewportSize(v);await page.addInitScript(()=>{Math.random=()=>0;});
  if(v.file)await page.context().setOffline(true);
  await page.goto(v.file?pathToFileURL(join(process.env.E2E_OUT_DIR,'index.html')).href+'#safemode':'/#safemode');
  await openWorkbenchMode(page,'study');await page.locator('[data-study-view=solutions]').click();
  await page.locator('[data-solution-pack]').selectOption('turn-river-half-pot');await page.locator('[data-solution-line]').click();
  await page.locator('[data-practice-config=solutionPlayer]').selectOption('1');await page.locator('[data-practice-action=start]').click();
  await expect(page.locator('.practice-context')).toContainText('IP（后行动）');
  await expect(page.locator('#practiceWorkspace .solution-values')).toHaveCount(0);
  await page.locator('[name=practiceChoice][value=check]').check();await page.locator('[data-practice-action=submit]').click();
  await page.locator('[data-practice-action=next]').click();await expect(page.locator('.practice-context')).toContainText('河牌');
  await page.locator('[name=practiceChoice][value=check]').check();await page.locator('[data-practice-action=submit]').click();
  await page.locator('[data-practice-action=review]').click();await page.locator('[data-practice-action=next]').click();
  const original=(await readPracticeState(page)).sessions[0];
  const question=original.questions.at(-1);expect(original.line.heroPlayer).toBe(1);
  await page.reload();await openWorkbenchMode(page,'practice');
  await expect(page.locator('.solution-review-queue')).toContainText('待复习求解节点 · 1');
  await page.locator('[data-practice-review-question]').click();
  await expect(page.locator('.practice-context')).toContainText('河牌');
  await expect(page.locator('#practiceWorkspace .solution-values')).toHaveCount(0);
  const replay=(await readPracticeState(page)).sessions.at(-1);
  expect(replay.questions).toHaveLength(1);expect(replay.questions[0]).toEqual(question);
  expect(replay.solutionSnapshot.contentHash).toBe(original.solutionSnapshot.contentHash);
  const compact=await page.evaluate(()=>JSON.parse(localStorage.getItem('pa_practice_v1')));
  expect(compact.version).toBe(2);expect(Object.keys(compact.solutionSnapshots)).toEqual([original.solutionSnapshot.contentHash]);
  expect(compact.sessions).toHaveLength(2);
  expect(compact.sessions.every(s=>!Object.hasOwn(s,'solutionSnapshot')&&s.solutionSnapshotHash===original.solutionSnapshot.contentHash)).toBe(true);
  await page.locator('[name=practiceChoice][value=check]').check();await page.locator('[data-practice-action=submit]').click();await page.locator('[data-practice-action=next]').click();
  await page.locator('#practiceContent details summary').click();await page.locator('[data-practice-solution-question]').click();
  await expect(page.locator('[data-solution-node-state]')).toContainText('当前由IP决策');
  await expect(page.locator('[data-solution-comparison]')).toBeVisible();
  await page.locator('[data-solution-compare-card]').selectOption('7h');
  await expect(page.locator('[data-solution-comparison]')).toContainText('公共牌配对');
  await expect(page.locator('[data-solution-comparison]')).toContainText('公共牌配对');
  await expect(page.locator('[data-solution-compare-practice]')).toBeDisabled();
  await page.locator('[data-solution-compare-card]').selectOption('Ah');
  await expect(page.locator('[data-solution-compare-practice]')).toBeEnabled();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:test.info().outputPath('river-comparison.png'),fullPage:true});
  await page.locator('[data-solution-compare-practice]').click();
  await page.locator('[data-practice-action=start]').click();
  const compared=(await readPracticeState(page)).sessions.at(-1);
  expect(compared.questions).toHaveLength(1);expect(compared.questions[0].context.board.at(-1)).toBe('Ah');
  expect(compared.questions[0].solution.combo).toBe(question.solution.combo);
  await expect(page.locator('#practiceWorkspace .solution-values')).toHaveCount(0);
  await page.locator('[data-practice-action=stop]').click();await page.locator('[data-practice-action=home]').click();
  await page.locator('[data-practice-review-remove]').click();await expect(page.locator('.solution-review-queue')).toHaveCount(0);
});
